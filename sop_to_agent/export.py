"""Write the compile results: spec, issues, tests, discovery report and a Shadow Eval domain file."""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml
from jinja2 import Environment, FileSystemLoader, select_autoescape

from .analyze import Issue
from .expr import describe
from .ingest import Document
from .pipeline import CompileResult
from .spec import Spec

TEMPLATES = Path(__file__).parent / "templates"


def shadow_eval_domain(spec: Spec, documents: list[Document]) -> dict[str, Any]:
    """A domain config for github.com/Aravindhant07/shadow-eval, so the agent can go straight into shadow mode."""
    outcomes = list(spec.outcomes)
    cost = []
    if "approve" in outcomes:
        for o in outcomes:
            if o != "approve" and o in ("decline", "reject", "deny"):
                cost.append({"agent": "approve", "truth": o, "cost": 20, "critical": True, "label": f"Approved when the rule says {o}"})
                cost.append({"agent": o, "truth": "approve", "cost": 15, "critical": True, "label": f"{o.capitalize()}d a case the rules approve"})
    segments = []
    for f in spec.inputs:
        if f.type == "enum":
            segments.append({"name": f.name, "field": f.name})
    numeric = [f for f in spec.inputs if f.type in ("number", "integer")]
    for f in numeric[:2]:
        ts = sorted({float(c.value) for r in spec.active_rules() for c in r.condition.comparisons if c.field == f.name})
        if ts:
            labels = [f"< {ts[0]:g}"] + [f"{a:g}–{b:g}" for a, b in zip(ts, ts[1:])] + [f"≥ {ts[-1]:g}"]
            segments.append({"name": f"{f.name}_band", "field": f.name, "bins": ts, "labels": labels})
    policy = "\n\n".join(d.text for d in documents)
    return {
        "name": spec.name,
        "description": f"Generated by sop-to-agent from {', '.join(spec.documents)}. Review costs and gates before use.",
        "case_id_field": "case_id",
        "display_fields": [f.name for f in spec.inputs],
        "decision": [{"name": spec.decision, "type": "enum", "values": outcomes, "description": "Outcome under the procedure."}],
        "primary_field": spec.decision,
        "cost_matrix": cost,
        "default_mismatch_cost": 5,
        "segments": segments,
        "readiness": {"min_cases": 30, "min_accuracy": 0.9, "max_critical_rate": 0.02, "max_cost_per_100": 60},
        "agent": {"system_prompt": "Decide each case by applying the procedure exactly, rule by rule. Report your confidence."},
        "policy": policy,
    }


def _issue_dict(i: Issue) -> dict[str, Any]:
    return asdict(i)


def render_report(res: CompileResult, documents: list[Document], fmt: str = "html") -> str:
    sentences = {s.id: s for d in documents for s in d.sentences}
    env = Environment(loader=FileSystemLoader(TEMPLATES), autoescape=select_autoescape(["html"]) if fmt == "html" else False,
                      trim_blocks=True, lstrip_blocks=True)
    env.filters["describe"] = describe
    tpl = env.get_template("report.html" if fmt == "html" else "report.md")
    counts: dict[str, int] = {}
    for i in res.issues:
        counts[i.severity] = counts.get(i.severity, 0) + 1
    return tpl.render(
        spec=res.spec, issues=res.issues, tests=res.tests, rejected=res.rejected, stats=res.stats,
        sentences=sentences, counts=counts, generated=datetime.now(timezone.utc).strftime("%d %b %Y, %H:%M UTC"),
        open_tests=sum(1 for t in res.tests if t.depends_on),
    )


def write_outputs(res: CompileResult, documents: list[Document], out_dir: str | Path) -> Path:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    res.spec.save(out / "spec.yaml")
    (out / "issues.json").write_text(json.dumps([_issue_dict(i) for i in res.issues], indent=1, default=str))
    with open(out / "tests.jsonl", "w") as fh:
        for t in res.tests:
            fh.write(json.dumps(asdict(t), default=str) + "\n")
    (out / "rejected.json").write_text(json.dumps(res.rejected, indent=1))
    (out / "stats.json").write_text(json.dumps(res.stats, indent=1))
    docs_dir = out / "documents"
    docs_dir.mkdir(exist_ok=True)
    for d in documents:
        (docs_dir / f"{d.name}.md").write_text(d.text)
    (out / "report.html").write_text(render_report(res, documents, "html"))
    (out / "report.md").write_text(render_report(res, documents, "md"))
    (out / "shadow_eval_domain.yaml").write_text(
        "# Shadow Eval domain config generated by sop-to-agent. Edit costs and gates before use.\n"
        + yaml.safe_dump(shadow_eval_domain(res.spec, documents), sort_keys=False, allow_unicode=True)
    )
    return out
